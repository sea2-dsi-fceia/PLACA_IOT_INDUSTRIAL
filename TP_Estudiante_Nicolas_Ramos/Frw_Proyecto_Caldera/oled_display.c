void oled_display_init(void)
{
#if defined(__ESP_IDF__) || defined(ESP_PLATFORM)
    if (oled_initialized) return;
    i2c_config_t conf = {
        .mode             = I2C_MODE_MASTER,
        .sda_io_num       = OLED_SDA,
        .scl_io_num       = OLED_SCL,
        .sda_pullup_en    = GPIO_PULLUP_ENABLE,
        .scl_pullup_en    = GPIO_PULLUP_ENABLE,
        .master.clk_speed = I2C_FREQ,
    };
    if (i2c_param_config(I2C_NUM, &conf) != ESP_OK)
        return;
    if (i2c_driver_install(I2C_NUM, conf.mode, 0, 0, 0) != ESP_OK)
        return;
    vTaskDelay(pdMS_TO_TICKS(100));
    oled_sh1106_init();
    oled_initialized = true;
#endif
}

void oled_clear(void)
{
#if defined(__ESP_IDF__) || defined(ESP_PLATFORM)
    if (!oled_initialized) return;
    uint8_t zero[31];
    memset(zero, 0, sizeof(zero));
    for (uint8_t page = 0; page < 8; page++) {
        oled_set_pos(page, 0);
        for (int n = 0; n < 132; n += 31) {
            int chunk = (132 - n) > 31 ? 31 : (132 - n);
            i2c_send_data(zero, chunk);
        }
    }
#endif
}

void oled_show(const char *texto)
{
#if defined(__ESP_IDF__) || defined(ESP_PLATFORM)
    if (!oled_initialized)
        oled_display_init();
    if (!texto) return;

    size_t len = strlen(texto);
    if (len > COLS) len = COLS;

    /* Ancho total en píxeles y columna de inicio para centrar */
    int total_w = (int)len * CHAR_W;
    uint8_t start_col = (OLED_ANCHO - total_w) / 2;
    if (start_col > 132 - total_w) start_col = 0;
    /* Página central para una línea (8 píxeles altos) */
    uint8_t page = (PAGES / 2) - 1;
    if (page > 7) page = 2;

    oled_clear();
    oled_set_pos(page, start_col);

    for (size_t i = 0; i < len; i++) {
        uint8_t c = (uint8_t)texto[i];
        if (c < 32 || c > 126) c = 32;
        const uint8_t *glyph = font_6x8[c - 32];
        i2c_send_data(glyph, CHAR_W);
    }
#endif
}
